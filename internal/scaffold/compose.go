package scaffold

import (
	"bytes"
	"text/template"
)

// Params describes the project-specific values scaffolded files are
// generated from.
type Params struct {
	AppName      string // lowercase, used for container_name prefixes (e.g. "myapp")
	AppPort      string // port the app listens on inside its container (e.g. "8080")
	MaxBodySize  string // nginx client_max_body_size, e.g. "50M" — should match the app's multipart max-request-size
	IncludeCerts bool   // mount ./certs into the app container (for RS256 JWT keys)
}

const composeTemplate = `# =============================================================
# {{.AppName}} — Production compose (generated by serv-kun springboot init)
#
# app       Spring Boot, built from ./Dockerfile or pulled from a registry
# postgres  self-hosted Postgres, not published to the host — only
#           reachable from other containers on the "internal" network
# backup    nightly pg_dump sidecar (see scripts/backup-postgres.sh)
# nginx     reverse proxy + TLS termination, the only service with
#           published ports
# certbot   issues/renews the Let's Encrypt certificate nginx serves
#
# Usage: sudo serv-kun springboot setup
# =============================================================
services:

  app:
    image: ${APP_IMAGE:?set APP_IMAGE in .env.prod}
    build: .
    container_name: {{.AppName}}-app
    restart: unless-stopped
    env_file:
      - .env.prod
    environment:
      SPRING_PROFILES_ACTIVE: prod
{{- if .IncludeCerts}}
    volumes:
      - ./certs:/etc/{{.AppName}}/certs:ro
{{- end}}
    depends_on:
      postgres:
        condition: service_healthy
    networks:
      - internal

  postgres:
    image: postgres:18-alpine
    container_name: {{.AppName}}-db
    restart: unless-stopped
    environment:
      POSTGRES_DB: ${POSTGRES_DB}
      POSTGRES_USER: ${POSTGRES_USER}
      POSTGRES_PASSWORD: ${POSTGRES_PASSWORD}
    volumes:
      - postgres-data:/var/lib/postgresql
    healthcheck:
      test: ["CMD-SHELL", "pg_isready -U ${POSTGRES_USER} -d ${POSTGRES_DB}"]
      interval: 10s
      timeout: 5s
      retries: 5
    networks:
      - internal

  backup:
    image: postgres:18-alpine
    container_name: {{.AppName}}-db-backup
    restart: unless-stopped
    environment:
      POSTGRES_HOST: postgres
      POSTGRES_DB: ${POSTGRES_DB}
      POSTGRES_USER: ${POSTGRES_USER}
      POSTGRES_PASSWORD: ${POSTGRES_PASSWORD}
      BACKUP_KEEP_DAYS: ${BACKUP_KEEP_DAYS:-7}
    entrypoint: ["/bin/sh", "/scripts/backup-postgres.sh"]
    volumes:
      - ./scripts/backup-postgres.sh:/scripts/backup-postgres.sh:ro
      - postgres-backups:/backups
    depends_on:
      postgres:
        condition: service_healthy
    networks:
      - internal

  nginx:
    image: nginx:1.27-alpine
    container_name: {{.AppName}}-nginx
    restart: unless-stopped
    ports:
      - "80:80"
      - "443:443"
    environment:
      APP_DOMAIN: ${APP_DOMAIN}
    # nginx reads certificates into memory at startup, so certbot renewing
    # them on disk is not enough on its own — without this reload loop nginx
    # would keep serving the old certificate until it expired, roughly 90
    # days after the first deploy.
    #
    # /docker-entrypoint.sh must be invoked explicitly. The nginx image only
    # runs its /docker-entrypoint.d/ scripts — which include the envsubst pass
    # that renders templates/ into conf.d/ — when the command starts with
    # "nginx". Overriding command with a shell skips that silently: nginx then
    # serves only its default site, the ACME challenge location doesn't exist,
    # and certificate issuance fails with a 404 on /.well-known/acme-challenge/.
    # exec keeps nginx as PID 1 so it still receives signals directly.
    command: >
      /bin/sh -c "while :; do sleep 6h & wait $${!}; nginx -s reload; done & exec /docker-entrypoint.sh nginx -g 'daemon off;'"
    volumes:
      - ./nginx/templates:/etc/nginx/templates:ro
      - ./nginx/conf.d/hardening.conf:/etc/nginx/conf.d/hardening.conf:ro
      - certbot-www:/var/www/certbot:ro
      - certbot-certs:/etc/letsencrypt:ro
    depends_on:
      - app
    networks:
      - internal

  certbot:
    image: certbot/certbot:latest
    container_name: {{.AppName}}-certbot
    restart: unless-stopped
    volumes:
      - certbot-www:/var/www/certbot
      - certbot-certs:/etc/letsencrypt
    entrypoint: >
      /bin/sh -c "trap exit TERM; while :; do certbot renew --webroot -w /var/www/certbot; sleep 12h & wait $${!}; done"

volumes:
  postgres-data:
    driver: local
  postgres-backups:
    driver: local
  certbot-www:
    driver: local
  certbot-certs:
    driver: local

networks:
  internal:
    driver: bridge
`

func renderCompose(p Params) (string, error) {
	return render("compose", composeTemplate, p)
}

func render(name, tmpl string, p Params) (string, error) {
	t, err := template.New(name).Parse(tmpl)
	if err != nil {
		return "", err
	}
	var buf bytes.Buffer
	if err := t.Execute(&buf, p); err != nil {
		return "", err
	}
	return buf.String(), nil
}
